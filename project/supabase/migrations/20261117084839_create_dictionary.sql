/*
# Create dictionary table for offline Arabic-English translation

1. New Tables
- `dictionary`
  - `id` (uuid, primary key)
  - `source_lang` (text, e.g. 'ar' or 'en')
  - `source_word` (text, the word/phrase in source language, normalized lowercase for english)
  - `target_lang` (text)
  - `target_word` (text, the translation)
  - `source_normalized` (text, normalized key for lookups: lowercased, trimmed)
  - `word_type` (text: 'word' or 'phrase')
  - `category` (text, semantic category: greeting, food, travel, etc.)
  - `created_at` (timestamp)
- Index on (source_lang, source_normalized) for fast lookups
- Index on (source_lang, source_word) for prefix/contains search

2. Security
- Enable RLS on `dictionary`.
- Grant SELECT to anon + authenticated — the dictionary is public/shared reference data (no auth in this app).
- No INSERT/UPDATE/DELETE via API — data is seeded via migration only.

3. Seed data
- Includes a curated set of common Arabic-English word and phrase pairs across categories:
  greetings, food, travel, numbers, family, time, weather, shopping, health, colors, animals, body, everyday phrases.
*/

CREATE TABLE IF NOT EXISTS dictionary (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  source_lang text NOT NULL,
  source_word text NOT NULL,
  target_lang text NOT NULL,
  target_word text NOT NULL,
  source_normalized text NOT NULL,
  word_type text NOT NULL DEFAULT 'word',
  category text NOT NULL DEFAULT 'general',
  created_at timestamptz DEFAULT now()
);

ALTER TABLE dictionary ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON dictionary TO anon, authenticated;

CREATE INDEX IF NOT EXISTS idx_dict_lookup ON dictionary (source_lang, source_normalized);
CREATE INDEX IF NOT EXISTS idx_dict_prefix ON dictionary (source_lang, source_word);

DROP POLICY IF EXISTS "anon_read_dictionary" ON dictionary;
CREATE POLICY "anon_read_dictionary"
ON dictionary FOR SELECT
TO anon, authenticated USING (true);

